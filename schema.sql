-- PetraRTW Database Schema
-- Matches class diagram exactly

-- Sales Admin
CREATE TABLE sales_admin (
    staff_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    staff_name VARCHAR(100),
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    staff_email VARCHAR(100),
    staff_address VARCHAR(255),
    staff_phone_num VARCHAR(20),
    profile_picture VARCHAR(500),
    PRIMARY KEY (staff_id)
);

-- Customers
CREATE TABLE customers (
    cust_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    cust_name VARCHAR(100),
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    cust_email VARCHAR(100),
    cust_address VARCHAR(255),
    cust_phone_num VARCHAR(20),
    PRIMARY KEY (cust_id)
);

-- Products
CREATE TABLE products (
    product_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    product_title VARCHAR(255) NOT NULL,
    product_price DECIMAL(10,2),
    product_desc LONG VARCHAR,
    product_image VARCHAR(500),
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    collection VARCHAR(100),
    item_type VARCHAR(20) DEFAULT 'cloth',
    size_s INTEGER DEFAULT 0,
    size_m INTEGER DEFAULT 0,
    size_l INTEGER DEFAULT 0,
    size_xl INTEGER DEFAULT 0,
    advertisement_id INTEGER,
    PRIMARY KEY (product_id)
);

-- Advertisements / Promotions
CREATE TABLE advertisements (
    ads_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    ads_title VARCHAR(255),
    ads_desc LONG VARCHAR,
    product_image VARCHAR(500),
    product_id INTEGER,
    start_date VARCHAR(20),
    end_date VARCHAR(20),
    status VARCHAR(20) DEFAULT 'draft',
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP,
    collection VARCHAR(100),
    staff_id INTEGER,
    PRIMARY KEY (ads_id)
);

-- Orders (renamed from purchases)
CREATE TABLE orders (
    order_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    cust_id INTEGER,
    order_num VARCHAR(20),
    payment_method VARCHAR(20),
    payment_gateway VARCHAR(30),
    gateway_ref VARCHAR(100),
    item_desc LONG VARCHAR,
    size VARCHAR(10),
    quantity INTEGER DEFAULT 1,
    item_sub_total DECIMAL(10,2),
    shipping_fee DECIMAL(10,2) DEFAULT 0,
    voucher_amount DECIMAL(10,2) DEFAULT 0,
    total_price DECIMAL(10,2),
    product_image VARCHAR(500),
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    product_id INTEGER,
    order_status VARCHAR(20) DEFAULT 'NEW',
    PRIMARY KEY (order_id)
);

-- Payments
CREATE TABLE payments (
    payment_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    order_id INTEGER NOT NULL,
    order_num VARCHAR(20) NOT NULL,
    payment_method VARCHAR(20) NOT NULL,
    gateway VARCHAR(30),
    gateway_ref VARCHAR(100),
    amount DECIMAL(10,2) NOT NULL,
    currency VARCHAR(3) DEFAULT 'MYR',
    status VARCHAR(20) DEFAULT 'INITIATED',
    error_code VARCHAR(50),
    error_message VARCHAR(255),
    paid_at TIMESTAMP,
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP,
    PRIMARY KEY (payment_id)
);

-- Issues / Complaints
CREATE TABLE issues (
    issue_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    ticket_num INTEGER,
    cust_id INTEGER,
    order_id INTEGER,
    order_num VARCHAR(20),
    title VARCHAR(255) NOT NULL,
    issue_desc LONG VARCHAR,
    product_image VARCHAR(500),
    status VARCHAR(20) DEFAULT 'New',
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    closed_time TIMESTAMP,
    staff_id INTEGER,
    PRIMARY KEY (issue_id)
);

-- Issue Chat
CREATE TABLE issue_chat (
    issue_chat_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    issue_id INTEGER NOT NULL,
    staff_id INTEGER,
    cust_id INTEGER,
    chat_text LONG VARCHAR NOT NULL,
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    issue_attachment VARCHAR(500),
    updated_time TIMESTAMP,
    reply_to_chat_id INTEGER,
    PRIMARY KEY (issue_chat_id)
);

-- Feedback
CREATE TABLE feedback (
    feedback_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    cust_id INTEGER,
    feedback_text LONG VARCHAR,
    product_image VARCHAR(500),
    status VARCHAR(20),
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    order_num VARCHAR(20),
    rating INTEGER,
    order_id INTEGER,
    product_name VARCHAR(255),
    PRIMARY KEY (feedback_id)
);

-- Cart (session cart stored in DB)
CREATE TABLE cart (
    cart_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
    cust_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    size VARCHAR(5) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (cart_id),
    FOREIGN KEY (cust_id) REFERENCES customers(cust_id),
    FOREIGN KEY (product_id) REFERENCES products(product_id)
);